'use strict';
const assert = require('node:assert/strict'), fs = require('node:fs'), vm = require('node:vm');
const window = {};
vm.runInNewContext(fs.readFileSync('bot-registry.js', 'utf8'), {window});
const now = Date.parse('2026-10-13T00:01:00Z');
const metadata = {run_id:'v2-paper-new', started_at:'2026-10-13T00:00:00Z'};
const report = {...metadata, available:true, observed_at:new Date(now).toISOString(), portfolio:{closed_trades:0}, history:[], open_trades:[]};
const accept = window.BotRegistry.currentReporting;
assert.equal(accept(report, now, metadata, now), report);
assert.equal(accept({...report,run_id:'v2-paper-old'}, now, metadata, now), null);
assert.equal(accept({...report,started_at:'2026-10-12T00:00:00Z'}, now, metadata, now), null);
assert.equal(accept({...report,started_at:'invalid'}, now, metadata, now), null);
assert.equal(accept(report, now, {...metadata,started_at:undefined}, now), null);
assert.equal(accept({...report,started_at:'2026-10-13T10:00:00+10:00'}, now, metadata, now).run_id, metadata.run_id);
assert.equal(accept(report, now-45001, metadata, now), null);
assert.equal(accept({...report,observed_at:new Date(now-45001).toISOString()}, now, metadata, now), null);
assert.equal(accept({...report,history:[{open_date:'2026-10-12T00:00:00Z'}]},now,metadata,now),null);
assert.equal(accept({...report,open_trades:[{open_date:'invalid'}]},now,metadata,now),null);
assert(accept({...report,open_trades:[{open_date:'2026-10-13 00:00:01'}]},now,metadata,now));
console.log('PASS paper reporting identity, epoch, timezone equivalence and stale response isolation');
const {currentRun,calculate}=require('./activity-performance.js');
const health={...metadata,mode:'PAPER',status:'available',stale:false,last_run:new Date(now).toISOString()};
const statuses=Object.fromEntries(['short','medium','long'].map((key,i)=>[key,{ok:true,generated_at:now/1000,bot:{mode:'PAPER',timeframe:['15m','1h','4h'][i],stake_currency:'USDT'},open_trades:[],history:[{id:99,profit_abs:999}],portfolio:{closed_trades:99}}]));
const reports=Object.fromEntries(['short','medium','long'].map(key=>[key,{...report,portfolio:{closed_trades:0}}]));
const scoped=currentRun(statuses,reports,health,now);
assert.equal(calculate(scoped,now).realized,0);
assert.equal(calculate(scoped,now).openCount,0);
assert.equal(calculate(scoped,now).count,0);
assert.equal(currentRun(statuses,{...reports,short:{...report,run_id:'v2-paper-old'}},health,now).short,null);
assert.equal(currentRun(statuses,reports,{...health,stale:true},now).short,null);
assert.equal(currentRun(statuses,reports,null,now).short,null);
assert.equal(currentRun(statuses,{...reports,short:{...report,history:[{id:99,open_date:'2026-10-12T00:00:00Z'}]}},health,now).short,null);
console.log('PASS homepage new-run zero, legacy performance exclusion and mixed/stale epoch rejection');
