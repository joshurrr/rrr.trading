const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const os = require('node:os');
(async () => {
 const browser=await chromium.launch({headless:true,channel:'msedge'});
 const page=await browser.newPage(); const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 let failure=false, stale=false, reportFailure=false;
 const expectedDay=()=>{const now=new Date();const hour=Number(new Intl.DateTimeFormat('en-AU',{timeZone:'Australia/Brisbane',hour:'2-digit',hourCycle:'h23'}).format(now));return new Intl.DateTimeFormat('en-CA',{timeZone:'Australia/Brisbane'}).format(hour<7?new Date(now.getTime()-86400000):now);};
 const today=()=>new Intl.DateTimeFormat('en-CA',{timeZone:'Australia/Brisbane'}).format(new Date());
 await page.route('https://stream.radiorrr.com/**',r=>r.abort());
 await page.route('**/data/daily-crypto-report.html',r=>reportFailure?r.fulfill({status:503}):r.continue());
 await page.route('https://api.rrr.trading/**',r=>{
  if(failure) return r.fulfill({status:503});
  const endpoint=new URL(r.request().url()).pathname;
  const data=endpoint==='/market-regime'?{market_regime:'neutral',average_confidence:64.1}:endpoint.startsWith('/api/reports/macro/')?{report_type:'macro_base',timezone:'Australia/Brisbane',report_date:stale?'2000-01-01':expectedDay(),generated_at:expectedDay()+'T07:00:00+10:00',macro_score:55,macro_regime:'Mixed',confidence:80,scoring:{coverage:0.8},components:Object.fromEntries(['rates','usd','equities','liquidity','volatility','macro_events'].map(k=>[k,{score:k==='macro_events'?null:55,status:'Mixed',summary:'Unavailable',provenance:{observations:k==='rates'?[{series_id:'DGS10',value:4.1,observation_date:today(),fresh:false}]:[]}}]))}:{};
  return r.fulfill({json:data});
 });
 await page.goto('http://localhost:8765');
 await page.waitForFunction(()=>document.querySelector('#assessment-regime').textContent==='NEUTRAL');
 assert.deepEqual(await page.locator('main > section').evaluateAll(es=>es.map(e=>e.id)),['','macro-base','market-inputs','daily-research','daily-assessment']);
 assert.equal(await page.locator('[data-report]').count(),7);
 assert.equal(await page.locator('#today,#reports,#daily-report,#bot-metrics').count(),0);
 assert.equal(await page.locator('#navigation [data-page=today]').count(),0);
 assert.match(await page.locator('#assessment-conviction').innerText(),/^64.1 \/ 100/);
 assert.equal(await page.locator('#assessment-trend').innerText(),'—');
 assert.equal(await page.locator('#macro-score').innerText(),'55');
 assert.match(await page.locator('#macro-components').textContent(),/stale, excluded/);
 assert.doesNotMatch(await page.locator('main .eyebrow').allTextContents().then(es=>es.join(' ')), /\d\d \//);
 assert.doesNotMatch(await page.locator('main').innerText(),/Awaiting analysis|Trading weight|Not configured/);
 assert.equal(await page.locator('#demo-summary,[data-paper]').count(),0);
 assert.equal(await page.locator('.input-card:visible').count(),1);
 assert(await page.locator('#assessment-trend').evaluate(el=>el.parentElement.hidden));
 for(const width of [320,375,768,1024,1440,1920]) {
  await page.setViewportSize({width,height:900});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Home overflow '+width);
 }
 await page.screenshot({path:path.join(os.tmpdir(),'rrr-homepage-desktop-check.png'),fullPage:true});
 await page.setViewportSize({width:375,height:900});
 await page.screenshot({path:path.join(os.tmpdir(),'rrr-homepage-mobile-check.png'),fullPage:true});
 stale=true; await page.evaluate(()=>refreshMacro());
 assert.equal(await page.locator('#macro-score').innerText(),'—');
 assert.match(await page.locator('#macro-summary').innerText(),/current 7 am Brisbane reporting cycle/);
 failure=true; await page.evaluate(()=>Promise.all([refreshRegime(),refreshMacro()]));
 assert.equal(await page.locator('#assessment-regime').innerText(),'—');
 assert.match(await page.locator('#assessment-status').innerText(),/unavailable/);
 assert.match(await page.locator('#macro-summary').innerText(),/unavailable/);
 await page.evaluate(()=>{const a=document.querySelector('audio');let paused=true;Object.defineProperty(a,'paused',{get:()=>paused});a.play=async()=>{paused=false;a.dispatchEvent(new Event('playing'));};a.pause=()=>{paused=true;a.dispatchEvent(new Event('pause'));};});
 assert.equal(await page.locator('audio').getAttribute('src'),'https://stream.radiorrr.com/radio.mp3');
 assert.equal(await page.locator('audio').evaluate(a=>a.autoplay),false);
 await page.locator('#radio-toggle').click(); assert.equal(await page.locator('#radio-toggle').getAttribute('aria-pressed'),'true');
 await page.locator('#radio-toggle').click(); assert.equal(await page.locator('#radio-toggle').getAttribute('aria-pressed'),'false');
 await page.goto('http://localhost:8765/reports.html');
 await page.waitForTimeout(200);
 assert(await page.locator('#today').isHidden());
 assert(await page.locator('#reports-empty').isVisible());
 assert.equal(await page.locator('#report-status').innerText(),'');
 assert.equal(await page.locator('#report-archive a').count(),0);
 assert.equal(await page.locator('#navigation [aria-current]').getAttribute('data-page'),'reports');
 for(const width of [320,375,768,1024,1440,1920]) {
  await page.setViewportSize({width,height:900});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Reports overflow '+width);
 }
 await page.screenshot({path:path.join(os.tmpdir(),'rrr-reports-desktop-check.png'),fullPage:true});
 await page.setViewportSize({width:375,height:900});
 await page.screenshot({path:path.join(os.tmpdir(),'rrr-reports-mobile-check.png'),fullPage:true});
 reportFailure=true; await page.goto('http://localhost:8765/reports.html');
 await page.waitForFunction(()=>document.querySelector('#report-status').textContent.includes('temporarily unavailable'));
 assert(await page.locator('#today').isHidden());
 assert(await page.locator('#reports-empty').isVisible());
 assert.deepEqual(errors,[]);
 await browser.close(); console.log('PASS: homepage hierarchy, macro/assessment fixtures, unavailable/stale states, reports empty/failure states, radio controls, no console errors; Home and Reports at 320/375/768/1024/1440/1920.');
})().catch(e=>{console.error(e);process.exitCode=1});
